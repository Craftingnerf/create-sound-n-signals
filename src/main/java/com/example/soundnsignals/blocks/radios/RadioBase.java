package com.example.soundnsignals.blocks.radios;

import com.simibubi.create.content.kinetics.base.DirectionalKineticBlock;
import com.simibubi.create.foundation.block.IBE;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.level.LevelReader;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockState;


abstract public class RadioBase<T extends RadioBlockEntity> extends DirectionalKineticBlock implements IBE<T> {
    public RadioBase(Properties properties) {
        super(properties);
    }

    @Override
    public Direction.Axis getRotationAxis(BlockState state) {
        return state.getValue(FACING).getAxis();
    }
    @Override
    public boolean hasShaftTowards(LevelReader world, BlockPos pos, BlockState state, Direction face) {
        return face == state.getValue(FACING);
    }

    @Override
    abstract public Class<T> getBlockEntityClass();

    @Override
    abstract public BlockEntityType<? extends T> getBlockEntityType();
}
